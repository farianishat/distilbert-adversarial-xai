def draw_token_row(ax, tokens, scores, changed_idxs, y_top, title, title_color, cmap, norm):
    """Draw wrapped color-coded token pills inside a Matplotlib axes and return bottom y."""
    ax.text(0.0, y_top, title, fontsize=9.2, fontweight="bold", color=title_color, va="top", ha="left")
    x = 0.0
    y = y_top - 0.16
    line_height = 0.18
    char_w = 0.0102
    pad_x = 0.013

    for idx_t, (tok, sc) in enumerate(zip(tokens, scores)):
        box_w = max(0.032, len(tok) * char_w + pad_x)
        if x + box_w > 0.99:
            x = 0.0
            y -= line_height
        rgba = cmap(norm(sc))
        is_changed = idx_t in changed_idxs
        edge_c = "#111111" if is_changed else "#CCCCCC"
        lw = 1.6 if is_changed else 0.5

        rect = patches.FancyBboxPatch(
            (x, y - 0.115),
            box_w,
            0.125,
            boxstyle="round,pad=0.008,rounding_size=0.012",
            facecolor=rgba,
            edgecolor=edge_c,
            linewidth=lw,
        )
        ax.add_patch(rect)
        lum = 0.299 * rgba[0] + 0.587 * rgba[1] + 0.114 * rgba[2]
        txt_color = "#FFFFFF" if lum < 0.48 else "#111111"
        ax.text(
            x + box_w / 2.0,
            y - 0.053,
            tok,
            fontsize=8.3,
            fontweight="bold" if is_changed else "normal",
            color=txt_color,
            ha="center",
            va="center",
            family="monospace",
        )
        x += box_w + 0.010
    return y - line_height


