"""---
## Section 4: Explainability with Captum Integrated Gradients

We use Captum's `LayerIntegratedGradients` on `base_model.distilbert.embeddings` to attribute model predictions back to input tokens for clean vs. adversarial sentence pairs.

- **Baseline reference:** `[CLS] [PAD] ... [PAD] [SEP]`
- **Target class:** Ground-truth class on clean text vs. flipped predicted class on adversarial text so we can directly observe **which tokens flip the decision**.
- **Outputs:**
  - `outputs/csv/ig_attributions_summary.csv` (summary across up to 50 pairs)
  - `outputs/html/token_attribution_heatmaps_5pairs.html` (color-coded HTML for 5 example pairs)
  - `outputs/figures/04_token_attribution_heatmaps_5pairs.png` & individual `04_token_attribution_pair_{1..5}.png` (**300 DPI PNGs**)

"""

from captum.attr import LayerIntegratedGradients
from IPython.display import display, HTML

def merge_wordpieces_and_scores(tokens, scores):
    """Merge WordPiece '##' subwords into readable words while summing attributions."""
    merged_tokens = []
    merged_scores = []
    for tok, sc in zip(tokens, scores):
        if tok in ("[CLS]", "[SEP]", "[PAD]"):
            continue
        if tok.startswith("##") and merged_tokens:
            merged_tokens[-1] = merged_tokens[-1] + tok[2:]
            merged_scores[-1] += float(sc)
        else:
            merged_tokens.append(tok)
            merged_scores.append(float(sc))
    arr = np.array(merged_scores, dtype=float)
    norm = np.linalg.norm(arr)
    if norm > 1e-8:
        arr = arr / norm
    return merged_tokens, arr


def build_distilbert_lig(model):
    def forward_func(input_ids, attention_mask):
        return model(input_ids=input_ids, attention_mask=attention_mask).logits
    return LayerIntegratedGradients(forward_func, model.distilbert.embeddings)


def compute_ig_for_text(
    text: str,
    target_class: int,
    model,
    tokenizer,
    lig: LayerIntegratedGradients,
    n_steps: int = 24,
    internal_batch_size: int = 8,
    max_length: int = 128,
    merge_wordpieces: bool = True,
) -> dict:
    model.eval()
    enc = tokenizer(
        text,
        return_tensors="pt",
        truncation=True,
        max_length=max_length,
    ).to(DEVICE)

    input_ids = enc["input_ids"]
    attention_mask = enc["attention_mask"]

    # Reference baseline: keep [CLS] and [SEP], replace all interior tokens with [PAD]
    ref_input_ids = torch.full_like(input_ids, tokenizer.pad_token_id)
    ref_input_ids[0, 0] = tokenizer.cls_token_id
    ref_input_ids[0, -1] = tokenizer.sep_token_id

    with torch.no_grad():
        logits = model(input_ids=input_ids, attention_mask=attention_mask).logits
        probs = F.softmax(logits, dim=-1).squeeze(0).cpu().numpy()
        pred_class = int(probs.argmax())
        pred_conf = float(probs[pred_class])

    attributions, delta = lig.attribute(
        inputs=input_ids,
        baselines=ref_input_ids,
        additional_forward_args=(attention_mask,),
        target=int(target_class),
        n_steps=int(n_steps),
        internal_batch_size=int(internal_batch_size),
        return_convergence_delta=True,
    )

    token_scores = attributions.sum(dim=-1).squeeze(0).detach().cpu().numpy()
    norm = np.linalg.norm(token_scores)
    if norm > 1e-8:
        token_scores = token_scores / norm

    raw_tokens = tokenizer.convert_ids_to_tokens(input_ids.squeeze(0).tolist())
    if merge_wordpieces:
        tokens, scores = merge_wordpieces_and_scores(raw_tokens, token_scores)
    else:
        keep = [i for i, t in enumerate(raw_tokens) if t not in ("[CLS]", "[SEP]", "[PAD]")]
        tokens = [raw_tokens[i] for i in keep]
        scores = token_scores[keep]

    return {
        "tokens": tokens,
        "scores": scores.tolist(),
        "pred_class": pred_class,
        "pred_conf": pred_conf,
        "prob_target": float(probs[int(target_class)]),
        "target_class": int(target_class),
        "convergence_delta": float(delta.item()) if delta.numel() == 1 else float(delta.mean().item()),
    }


def select_balanced_ig_pairs(df_succ: pd.DataFrame, total_pairs: int, recipes) -> pd.DataFrame:
    """Select a balanced set of successful pairs across all attack methods."""
    per_method = max(1, total_pairs // max(len(recipes), 1))
    picked = []
    used_idx = set()

    for recipe in recipes:
        sub = df_succ[df_succ["attack_method"] == recipe].sort_values(
            ["semantic_similarity", "confidence_drop"], ascending=[False, False]
        )
        chosen = sub.head(per_method)
        picked.append(chosen)
        used_idx.update(chosen.index.tolist())

    df_out = pd.concat(picked, ignore_index=False)
    remaining = total_pairs - len(df_out)
    if remaining > 0:
        leftover = df_succ.drop(index=list(used_idx), errors="ignore").head(remaining)
        df_out = pd.concat([df_out, leftover], ignore_index=False)

    return df_out.reset_index(drop=True)

def find_changed_positions(tokens, sub_words):
    """Return token indices matching substituted words, including split contractions like n't -> [n, ', t]."""
    toks_l = [t.lower() for t in tokens]
    idxs = set()
    for sw in sub_words:
        sw_c = sw.lower().strip(".,!?;:\"")
        sw_no_apos = sw_c.strip("'")
        for i, t in enumerate(toks_l):
            if t == sw_c or (sw_no_apos and t == sw_no_apos):
                idxs.add(i)
        if sw_c == "n't":
            for i in range(len(toks_l) - 2):
                if toks_l[i : i + 3] == ["n", "'", "t"]:
                    idxs.update([i, i + 1, i + 2])
    return idxs


def build_ig_summary_df(records) -> pd.DataFrame:
    """Build contraction-aware IG summary DataFrame from ig_records."""
    summary_rows = []
    for rec in records:
        orig_ig = rec["orig_ig"]
        adv_ig = rec["adv_ig"]
        subs = rec.get("substitutions", [])
        orig_changed_pos = find_changed_positions(orig_ig["tokens"], [w[0] for w in subs])

        orig_top_idx = int(np.argmax(orig_ig["scores"])) if orig_ig["scores"] else 0
        adv_top_idx = int(np.argmax(adv_ig["scores"])) if adv_ig["scores"] else 0
        top3_orig_pos = set(np.argsort(orig_ig["scores"])[-3:].tolist()) if orig_ig["scores"] else set()
        attacked_top3 = bool(top3_orig_pos & orig_changed_pos)

        summary_rows.append({
            "pair_id": int(rec["pair_id"]),
            "sample_idx": int(rec["sample_idx"]),
            "attack_method": rec["attack_method"],
            "ground_truth": int(rec["ground_truth"]),
            "adv_pred": int(rec["adv_pred"]),
            "orig_top_token": orig_ig["tokens"][orig_top_idx] if orig_ig["tokens"] else "",
            "orig_top_score": round(float(orig_ig["scores"][orig_top_idx]), 4) if orig_ig["scores"] else 0.0,
            "adv_top_token": adv_ig["tokens"][adv_top_idx] if adv_ig["tokens"] else "",
            "adv_top_score": round(float(adv_ig["scores"][adv_top_idx]), 4) if adv_ig["scores"] else 0.0,
            "attacked_top3_salient_token": attacked_top3,
            "orig_convergence_delta": round(float(orig_ig["convergence_delta"]), 5),
            "adv_convergence_delta": round(float(adv_ig["convergence_delta"]), 5),
            "semantic_similarity": round(float(rec["semantic_similarity"]), 4),
            "confidence_drop": round(float(rec["confidence_drop"]), 4),
        })
    return pd.DataFrame(summary_rows)


