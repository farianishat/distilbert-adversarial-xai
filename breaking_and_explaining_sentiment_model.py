def pick_showcase_pairs(records, k: int = 5):
    """Pick k diverse, concise, high-impact pairs covering all attack methods."""
    def rank_key(r):
        n_tok = len(r["orig_ig"]["tokens"])
        len_penalty = 0.0 if n_tok <= 28 else -0.25 * (n_tok - 28) / 20.0
        return r["semantic_similarity"] + r["confidence_drop"] + len_penalty

    by_method = {}
    for r in records:
        by_method.setdefault(r["attack_method"], []).append(r)
    for m in by_method:
        by_method[m].sort(key=rank_key, reverse=True)

    selected = []
    seen = set()
    methods = list(CFG["attacks"]["recipes"])
    idx_ptr = {m: 0 for m in methods}
    while len(selected) < min(k, len(records)):
        added_any = False
        for m in methods:
            pool = by_method.get(m, [])
            while idx_ptr[m] < len(pool) and pool[idx_ptr[m]]["pair_id"] in seen:
                idx_ptr[m] += 1
            if idx_ptr[m] < len(pool) and len(selected) < k:
                cand = pool[idx_ptr[m]]
                idx_ptr[m] += 1
                seen.add(cand["pair_id"])
                selected.append(cand)
                added_any = True
        if not added_any:
            break
    return selected


def score_to_rgba_css(score: float, max_abs: float = 1.0) -> str:
    val = np.clip(score / max(max_abs, 1e-6), -1.0, 1.0)
    alpha = 0.12 + 0.72 * abs(val)
    if val >= 0:
        return f"rgba(34, 153, 84, {alpha:.2f})"
    return f"rgba(203, 67, 53, {alpha:.2f})"


