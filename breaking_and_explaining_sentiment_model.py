"""---
## Section 5: Adversarial Augmentation Defense (1 Epoch) & Re-Attack

To harden the sentiment model without leaking any validation examples:
1. Sample candidate sentences strictly from the **SST-2 `train` split** and generate adversarial examples using a fast mix of attacks (`defense.adv_generation_recipes`).
2. Combine the adversarial examples (labeled with their **true** sentiment label) with clean `train` examples to prevent clean accuracy degradation.
3. Fine-tune DistilBERT for **1 epoch** on CPU using `AdamW` + linear warmup scheduler.
4. Re-evaluate clean accuracy on all 872 validation sentences and **re-attack** the defended model on the exact same validation subset with **TextFooler, DeepWordBug, and PWWS**.

"""

def generate_train_adversarial_examples(model, tokenizer, train_dataset, cfg: dict) -> pd.DataFrame:
    """Harvest adversarial examples strictly from SST-2 train split (zero validation leakage)."""
    cache_path = DIRS["csv_dir"] / "defense_adv_train_examples.csv"
    if cache_path.exists() and cfg["project"].get("resume_from_cache", True):
        print(f"[CACHE] Loading cached adversarial training set from {cache_path}")
        return pd.read_csv(cache_path)

    seed_everything(SEED + 100)
    recipes = cfg["defense"]["adv_generation_recipes"]
    target_total = int(cfg["defense"]["num_adv_examples"])
    per_recipe_target = math.ceil(target_total / max(len(recipes), 1))
    max_candidates = int(cfg["defense"]["max_train_candidates"])

    cand_indices = make_stratified_indices(
        train_dataset["label"], num_samples=max_candidates, seed=SEED + 100, stratified=True
    )
    cand_pairs = [(train_dataset[int(i)]["sentence"], int(train_dataset[int(i)]["label"])) for i in cand_indices]

    model.eval()
    model_wrapper = HuggingFaceModelWrapper(model, tokenizer)

    harvested = []
    chunk_size = max(1, len(cand_pairs) // max(len(recipes), 1))

    for r_idx, recipe_name in enumerate(recipes):
        sub_pairs = cand_pairs[r_idx * chunk_size : (r_idx + 1) * chunk_size]
        attack = build_attack_recipe(recipe_name, model_wrapper, cfg)
        attack.goal_function.query_budget = min(int(cfg["attacks"].get("query_budget", 200)), 150)

        collected = 0
        for sent, lbl in tqdm(sub_pairs, desc=f"Harvest adv train ({recipe_name})"):
            if collected >= per_recipe_target:
                break
            try:
                res = attack.attack(sent, lbl)
                if isinstance(res, SuccessfulAttackResult):
                    harvested.append({
                        "sentence": res.perturbed_text(),
                        "label": int(lbl),
                        "source": f"adv_{recipe_name}",
                        "original_sentence": sent,
                    })
                    collected += 1
            except Exception:
                continue

        print(f"Harvested {collected} adversarial train examples via {recipe_name}.")

    df_adv_train = pd.DataFrame(harvested[:target_total])
    df_adv_train.to_csv(cache_path, index=False)
    print(f"[SAVED] {cache_path} ({len(df_adv_train)} adversarial training examples)")
    return df_adv_train


class SimpleTextDataset(TorchDataset):
    def __init__(self, texts, labels, tokenizer, max_length=96):
        self.encodings = tokenizer(
            list(texts),
            truncation=True,
            padding=True,
            max_length=max_length,
            return_tensors="pt",
        )
        self.labels = torch.tensor(list(labels), dtype=torch.long)

    def __len__(self):
        return len(self.labels)

    def __getitem__(self, idx):
        item = {k: v[idx] for k, v in self.encodings.items()}
        item["labels"] = self.labels[idx]
        return item


def finetune_defended_model(df_adv_train: pd.DataFrame, train_dataset, tokenizer, cfg: dict):
    """Fine-tune DistilBERT for 1 epoch on clean + adversarial train examples on CPU."""
    save_dir = DIRS["models_dir"] / "defended_distilbert_sst2"
    if (save_dir / "config.json").exists() and cfg["project"].get("resume_from_cache", True):
        print(f"[CACHE] Loading defended model from {save_dir}")
        model = AutoModelForSequenceClassification.from_pretrained(save_dir)
        model.to(DEVICE)
        model.eval()
        return model

    seed_everything(SEED + 200)
    n_clean = int(cfg["defense"]["num_clean_examples"])
    clean_idx = make_stratified_indices(train_dataset["label"], num_samples=n_clean, seed=SEED + 200, stratified=True)
    df_clean_train = pd.DataFrame({
        "sentence": [train_dataset[int(i)]["sentence"] for i in clean_idx],
        "label": [int(train_dataset[int(i)]["label"]) for i in clean_idx],
        "source": "clean_train",
    })

    df_mix = pd.concat([
        df_clean_train[["sentence", "label", "source"]],
        df_adv_train[["sentence", "label", "source"]],
    ], ignore_index=True).sample(frac=1.0, random_state=SEED).reset_index(drop=True)

    print(f"Adversarial training mix: {len(df_mix)} examples ({df_mix['source'].value_counts().to_dict()})")

    train_torch_ds = SimpleTextDataset(
        df_mix["sentence"].tolist(),
        df_mix["label"].tolist(),
        tokenizer,
        max_length=int(cfg["defense"]["train_max_length"]),
    )
    train_loader = DataLoader(
        train_torch_ds,
        batch_size=int(cfg["defense"]["batch_size"]),
        shuffle=True,
    )

    defended_model = AutoModelForSequenceClassification.from_pretrained(cfg["model"]["pretrained_name"])
    defended_model.to(DEVICE)
    defended_model.train()

    epochs = int(cfg["defense"]["epochs"])
    optimizer = torch.optim.AdamW(
        defended_model.parameters(),
        lr=float(cfg["defense"]["learning_rate"]),
        weight_decay=float(cfg["defense"]["weight_decay"]),
    )
    total_steps = len(train_loader) * epochs
    warmup_steps = int(total_steps * float(cfg["defense"]["warmup_ratio"]))
    scheduler = get_linear_schedule_with_warmup(optimizer, num_warmup_steps=warmup_steps, num_training_steps=total_steps)

    for epoch in range(1, epochs + 1):
        running_loss = 0.0
        pbar = tqdm(train_loader, desc=f"Defense Fine-Tune Epoch {epoch}/{epochs}")
        for step, batch in enumerate(pbar, 1):
            optimizer.zero_grad()
            outputs = defended_model(
                input_ids=batch["input_ids"].to(DEVICE),
                attention_mask=batch["attention_mask"].to(DEVICE),
                labels=batch["labels"].to(DEVICE),
            )
            loss = outputs.loss
            loss.backward()
            torch.nn.utils.clip_grad_norm_(defended_model.parameters(), float(cfg["defense"]["max_grad_norm"]))
            optimizer.step()
            scheduler.step()
            running_loss += float(loss.item())
            pbar.set_postfix({"loss": f"{running_loss / step:.4f}"})

    defended_model.eval()
    save_dir.mkdir(parents=True, exist_ok=True)
    defended_model.save_pretrained(save_dir)
    tokenizer.save_pretrained(save_dir)
    print(f"[SAVED] Defended model checkpoint -> {save_dir}")
    return defended_model


