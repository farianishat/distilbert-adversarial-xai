@torch.no_grad()
def predict_proba(
    texts,
    model,
    tokenizer,
    batch_size: int = 32,
    max_length: int = 128,
    device: torch.device = DEVICE,
) -> np.ndarray:
    """Return softmax probabilities of shape (N, 2) on CPU."""
    model.eval()
    all_probs = []
    for i in range(0, len(texts), batch_size):
        batch = texts[i : i + batch_size]
        enc = tokenizer(
            batch,
            padding=True,
            truncation=True,
            max_length=max_length,
            return_tensors="pt",
        ).to(device)
        logits = model(**enc).logits
        probs = F.softmax(logits, dim=-1).cpu().numpy()
        all_probs.append(probs)
    return np.vstack(all_probs) if all_probs else np.empty((0, 2))


def evaluate_clean_model(model, tokenizer, dataset, tag: str = "baseline"):
    sentences = list(dataset["sentence"])
    labels = np.array(dataset["label"], dtype=int)

    probs = predict_proba(
        sentences,
        model,
        tokenizer,
        batch_size=int(CFG["model"]["eval_batch_size"]),
        max_length=int(CFG["data"]["max_length"]),
    )
    preds = probs.argmax(axis=1)
    pred_conf = probs.max(axis=1)
    true_label_conf = probs[np.arange(len(labels)), labels]

    acc = float(accuracy_score(labels, preds))
    f1 = float(f1_score(labels, preds))
    cm = confusion_matrix(labels, preds).tolist()

    df_eval = pd.DataFrame({
        "sample_idx": np.arange(len(sentences)),
        "sentence": sentences,
        "ground_truth": labels,
        "prediction": preds,
        "correct": (preds == labels),
        "prob_neg": probs[:, 0],
        "prob_pos": probs[:, 1],
        "pred_confidence": pred_conf,
        "true_label_confidence": true_label_conf,
    })

    metrics = {
        "tag": tag,
        "num_samples": len(sentences),
        "clean_accuracy": acc,
        "f1_score": f1,
        "mean_pred_confidence": float(pred_conf.mean()),
        "median_pred_confidence": float(np.median(pred_conf)),
        "p10_pred_confidence": float(np.percentile(pred_conf, 10)),
        "confusion_matrix": cm,
    }

    df_eval.to_csv(DIRS["csv_dir"] / f"{tag}_clean_predictions.csv", index=False)
    with open(DIRS["csv_dir"] / f"{tag}_clean_metrics.json", "w", encoding="utf-8") as f:
        json.dump(metrics, f, indent=2)

    return df_eval, metrics


