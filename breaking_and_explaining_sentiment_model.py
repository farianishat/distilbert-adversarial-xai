def make_stratified_indices(labels, num_samples: int, seed: int = 42, stratified: bool = True):
    """Return deterministic indices into dataset split."""
    n_total = len(labels)
    num_samples = min(int(num_samples), n_total)
    rng = np.random.default_rng(seed)

    if not stratified:
        idx = rng.choice(n_total, size=num_samples, replace=False)
        return sorted(idx.tolist())

    labels_arr = np.asarray(labels)
    idx_0 = np.where(labels_arr == 0)[0]
    idx_1 = np.where(labels_arr == 1)[0]
    n0 = num_samples // 2
    n1 = num_samples - n0
    chosen_0 = rng.choice(idx_0, size=min(n0, len(idx_0)), replace=False)
    chosen_1 = rng.choice(idx_1, size=min(n1, len(idx_1)), replace=False)
    combined = np.concatenate([chosen_0, chosen_1])
    rng.shuffle(combined)
    return combined.tolist()


