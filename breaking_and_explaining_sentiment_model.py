class SemanticSimilarityScorer:
    """Computes cosine semantic similarity between original and adversarial sentence pairs."""

    def __init__(self, cfg: dict):
        self.backend = cfg["similarity"]["backend"].lower()
        self.batch_size = int(cfg["similarity"]["batch_size"])
        self.model = None

        if self.backend == "use":
            try:
                import tensorflow_hub as hub
                self.model = hub.load(cfg["similarity"]["use_hub_url"])
                print("Loaded Universal Sentence Encoder (TensorFlow Hub).")
            except Exception as exc:
                print(f"[WARN] Could not load TF-Hub USE ({exc}). Falling back to sentence-transformers.")
                self.backend = "sentence_transformers"

        if self.backend == "sentence_transformers":
            from sentence_transformers import SentenceTransformer
            st_name = cfg["similarity"]["st_model_name"]
            self.model = SentenceTransformer(st_name, device="cpu")
            print(f"Loaded SentenceTransformer on CPU: {st_name}")

    def score_pairs(self, orig_texts, adv_texts) -> np.ndarray:
        if not orig_texts:
            return np.array([], dtype=float)

        if self.backend == "use":
            emb_a = self.model(orig_texts).numpy()
            emb_b = self.model(adv_texts).numpy()
            norm_a = np.linalg.norm(emb_a, axis=1, keepdims=True) + 1e-12
            norm_b = np.linalg.norm(emb_b, axis=1, keepdims=True) + 1e-12
            sims = np.sum((emb_a / norm_a) * (emb_b / norm_b), axis=1)
            return np.clip(sims, -1.0, 1.0)

        emb_a = self.model.encode(
            orig_texts, batch_size=self.batch_size, normalize_embeddings=True, show_progress_bar=False
        )
        emb_b = self.model.encode(
            adv_texts, batch_size=self.batch_size, normalize_embeddings=True, show_progress_bar=False
        )
        sims = np.sum(emb_a * emb_b, axis=1)
        return np.clip(sims, -1.0, 1.0)


