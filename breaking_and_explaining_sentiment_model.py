def build_attack_recipe(recipe_name: str, model_wrapper, cfg: dict):
    """Build TextAttack recipe with CPU query budget and optional TF-free fallback for TextFooler."""
    name = recipe_name.lower().strip()
    query_budget = cfg["attacks"].get("query_budget", None)

    if name == "textfooler":
        try:
            attack = TextFoolerJin2019.build(model_wrapper)
            for c in attack.constraints:
                if isinstance(c, UniversalSentenceEncoder):
                    _ = c.model
        except Exception as exc:
            if not cfg["attacks"].get("allow_textfooler_no_tf_fallback", True):
                raise
            print(f"[WARN] TextFooler USE constraint unavailable ({type(exc).__name__}: {exc}).")
            print("       Removing TF-Hub USE constraint; WordEmbeddingDistance & POS constraints remain active.")
            attack = TextFoolerJin2019.build(model_wrapper)
            attack.constraints = [
                c for c in attack.constraints if not isinstance(c, UniversalSentenceEncoder)
            ]
    elif name == "deepwordbug":
        attack = DeepWordBugGao2018.build(model_wrapper)
    elif name == "pwws":
        attack = PWWSRen2019.build(model_wrapper)
    else:
        raise ValueError(f"Unsupported recipe_name: {recipe_name}")

    if query_budget is not None:
        attack.goal_function.query_budget = int(query_budget)

    return attack


def extract_word_diff(result):
    """Extract number of words changed, fraction changed, and (orig_word, adv_word) substitutions."""
    orig_at = result.original_result.attacked_text
    adv_at = result.perturbed_result.attacked_text
    orig_words = list(orig_at.words)
    adv_words = list(adv_at.words)
    n_orig = max(len(orig_words), 1)

    substitutions = []
    if len(orig_words) == len(adv_words):
        diff_indices = sorted(orig_at.all_words_diff(adv_at))
        for idx in diff_indices:
            if idx < len(orig_words) and idx < len(adv_words):
                substitutions.append((orig_words[idx], adv_words[idx]))
        words_changed = len(diff_indices)
    else:
        sm = difflib.SequenceMatcher(None, orig_words, adv_words)
        words_changed = 0
        for tag, i1, i2, j1, j2 in sm.get_opcodes():
            if tag == "replace":
                for ow, aw in zip(orig_words[i1:i2], adv_words[j1:j2]):
                    substitutions.append((ow, aw))
                words_changed += max(i2 - i1, j2 - j1)
            elif tag in ("delete", "insert"):
                words_changed += max(i2 - i1, j2 - j1)

    pct_changed = 100.0 * words_changed / n_orig
    return int(words_changed), float(pct_changed), substitutions


def run_single_attack(
    recipe_name: str,
    model,
    tokenizer,
    pairs,
    sample_indices,
    cfg: dict,
    tag: str = "baseline",
    force_rerun: bool = False,
) -> pd.DataFrame:
    """Run one TextAttack recipe, score exact probabilities & semantic similarity, and cache CSV."""
    cache_path = DIRS["csv_dir"] / f"{tag}_{recipe_name}_detailed.csv"
    if cache_path.exists() and cfg["project"].get("resume_from_cache", True) and not force_rerun:
        print(f"[CACHE] Loading cached results from {cache_path}")
        return pd.read_csv(cache_path)

    seed_everything(SEED)
    model.eval()
    model_wrapper = HuggingFaceModelWrapper(model, tokenizer)
    attack = build_attack_recipe(recipe_name, model_wrapper, cfg)

    ta_dataset = TextAttackDataset(pairs)
    attack_args = AttackArgs(
        num_examples=len(pairs),
        disable_stdout=bool(cfg["attacks"].get("disable_textattack_stdout", True)),
        random_seed=SEED,
        shuffle=False,
        silent=True,
    )

    t0 = time.perf_counter()
    attacker = Attacker(attack, ta_dataset, attack_args)
    results = attacker.attack_dataset()
    elapsed = time.perf_counter() - t0

    orig_texts = [r.original_text() for r in results]
    adv_texts = [r.perturbed_text() for r in results]

    orig_probs = predict_proba(
        orig_texts, model, tokenizer,
        batch_size=int(cfg["model"]["eval_batch_size"]),
        max_length=int(cfg["data"]["max_length"]),
    )
    adv_probs = predict_proba(
        adv_texts, model, tokenizer,
        batch_size=int(cfg["model"]["eval_batch_size"]),
        max_length=int(cfg["data"]["max_length"]),
    )
    sim_scores = sim_scorer.score_pairs(orig_texts, adv_texts)

    rows = []
    for k, res in enumerate(results):
        if isinstance(res, SuccessfulAttackResult):
            status = "Successful"
        elif isinstance(res, FailedAttackResult):
            status = "Failed"
        elif isinstance(res, SkippedAttackResult):
            status = "Skipped"
        else:
            status = type(res).__name__

        gt = int(pairs[k][1])
        orig_pred = int(orig_probs[k].argmax())
        adv_pred = int(adv_probs[k].argmax())
        orig_conf_gt = float(orig_probs[k, gt])
        adv_conf_gt = float(adv_probs[k, gt])
        adv_pred_conf = float(adv_probs[k].max())
        conf_drop = orig_conf_gt - adv_conf_gt

        words_changed, pct_words_changed, subs = extract_word_diff(res)

        rows.append({
            "run_tag": tag,
            "attack_method": recipe_name,
            "sample_idx": int(sample_indices[k]),
            "status": status,
            "ground_truth": gt,
            "orig_pred": orig_pred,
            "adv_pred": adv_pred,
            "orig_conf": orig_conf_gt,
            "adv_conf_on_orig_label": adv_conf_gt,
            "adv_pred_conf": adv_pred_conf,
            "confidence_drop": conf_drop,
            "words_changed": words_changed,
            "pct_words_changed": pct_words_changed,
            "num_queries": int(res.num_queries),
            "semantic_similarity": float(sim_scores[k]),
            "original_text": orig_texts[k],
            "perturbed_text": adv_texts[k],
            "word_substitutions": json.dumps(subs),
            "attack_runtime_sec": elapsed,
        })

    df = pd.DataFrame(rows)
    df.to_csv(cache_path, index=False)
    print(f"[SAVED] {cache_path} ({len(df)} rows, {elapsed:.1f}s)")
    return df


def summarize_attack_df(df_all: pd.DataFrame) -> pd.DataFrame:
    """Compute clean summary metrics table by attack method."""
    summary_rows = []
    for method, grp in df_all.groupby("attack_method", sort=False):
        n_total = len(grp)
        n_skipped = int((grp["status"] == "Skipped").sum())
        n_success = int((grp["status"] == "Successful").sum())
        n_failed = int((grp["status"] == "Failed").sum())
        n_clean_correct = n_total - n_skipped

        orig_acc = 100.0 * n_clean_correct / max(n_total, 1)
        under_attack_acc = 100.0 * n_failed / max(n_total, 1)
        asr = 100.0 * n_success / max(n_clean_correct, 1)

        succ = grp[grp["status"] == "Successful"]
        summary_rows.append({
            "run_tag": grp["run_tag"].iloc[0],
            "attack_method": method,
            "num_attempted": n_total,
            "num_clean_correct": n_clean_correct,
            "num_successful": n_success,
            "num_failed": n_failed,
            "num_skipped": n_skipped,
            "original_accuracy_pct": round(orig_acc, 2),
            "under_attack_accuracy_pct": round(under_attack_acc, 2),
            "attack_success_rate_pct": round(asr, 2),
            "avg_words_changed": round(float(succ["words_changed"].mean()), 2) if len(succ) else 0.0,
            "median_words_changed": round(float(succ["words_changed"].median()), 2) if len(succ) else 0.0,
            "avg_pct_words_changed": round(float(succ["pct_words_changed"].mean()), 2) if len(succ) else 0.0,
            "avg_queries": round(float(grp[grp["status"] != "Skipped"]["num_queries"].mean()), 2) if n_clean_correct else 0.0,
            "avg_semantic_similarity": round(float(succ["semantic_similarity"].mean()), 4) if len(succ) else 0.0,
            "avg_confidence_drop": round(float(succ["confidence_drop"].mean()), 4) if len(succ) else 0.0,
            "runtime_sec": round(float(grp["attack_runtime_sec"].iloc[0]), 1),
        })
    return pd.DataFrame(summary_rows)

